#!/usr/bin/env python3
"""Prepare branch photos without removing previously published galleries.

Workflow:
  1. Put new/updated JPEG, PNG, or WebP originals in
     assets/branches/<branch-id>/input/ (cover.jpg selects the thumbnail).
  2. Run: python3 -m pip install Pillow
  3. Run: python3 tools/prepare_photos.py

Only branches containing files in input/ are reprocessed. Existing .webp
photos in other branches are preserved and rediscovered automatically.
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
BRANCHES = ROOT / 'assets' / 'branches'
MANIFEST = ROOT / 'assets' / 'js' / 'branch-photos.js'
EXTENSIONS = {'.jpg', '.jpeg', '.png', '.webp', '.tif', '.tiff'}
MAX_SIZE = 1600
WEBP_QUALITY = 90


def order_key(path: Path) -> tuple[int, str]:
    """Put the selected cover first and sort extra photos naturally."""
    stem = path.stem.lower()
    cover = stem in {'cover', 'main', 'primary', '01', '1'}
    return (0 if cover else 1, re.sub(r'\d+', lambda m: m.group().zfill(8), stem))


def convert(source: Path, destination: Path) -> None:
    """Auto-orient, resize with aspect ratio preserved, optimize as WebP."""
    with Image.open(source) as original:
        # JPEG decoder can reduce very large originals before full decoding.
        original.draft('RGB', (MAX_SIZE, MAX_SIZE))
        image = ImageOps.exif_transpose(original)
        image.thumbnail((MAX_SIZE, MAX_SIZE), Image.Resampling.LANCZOS)
        if image.mode not in {'RGB', 'RGBA'}:
            image = image.convert('RGB')
        image.save(destination, 'WEBP', quality=WEBP_QUALITY, method=2)


def main() -> None:
    manifest: dict[str, list[str]] = {}
    processed = 0
    for branch in sorted(BRANCHES.iterdir()):
        if not branch.is_dir():
            continue
        originals = branch / 'input'
        sources = []
        if originals.is_dir():
            sources = sorted(
                (p for p in originals.iterdir() if p.is_file() and p.suffix.lower() in EXTENSIONS),
                key=order_key,
            )
        if sources:
            # Replacing one branch never affects any other existing gallery.
            for old_photo in branch.glob('*.webp'):
                old_photo.unlink()
            for index, source in enumerate(sources):
                filename = 'cover.webp' if index == 0 else f'{index + 1:02d}.webp'
                convert(source, branch / filename)
                print(f'{branch.name}: {source.name} → {filename}')
                processed += 1
        # Include already-optimized photos even when this branch's input is empty.
        webps = sorted(branch.glob('*.webp'), key=order_key)
        if webps:
            manifest[branch.name] = [p.relative_to(ROOT).as_posix() for p in webps]
    MANIFEST.write_text(
        '/* Automatically generated by tools/prepare_photos.py */\n'
        'window.ZOOAREA_BRANCH_PHOTOS = '
        + json.dumps(manifest, ensure_ascii=False, indent=2)
        + ';\n',
        encoding='utf-8',
    )
    print(f'Complete: {len(manifest)} galleries; {processed} new/updated photos processed.')


if __name__ == '__main__':
    main()
